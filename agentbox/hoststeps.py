"""The Host steps of agentbox setup (#102): what a Host installed from the RPM, which opens,
enables and writes nothing on its own (ADR 0009), still needs before its VMs run.

Every step changes only what differs from how it should be and returns what it changed, as
lines for people, so running setup again changes nothing. No step overwrites a record of the
Host: the lists a new Host starts with go only where there is neither the record nor the text
file it came from nor that file moved aside by its migration, and Settings, the VM registry,
the certificate and the GitHub App are not touched here at all. Files are replaced whole
(state_files.write_atomic), so a step that fails leaves none half-written. A failure ends the
command (Fail); setup says which step it was.
"""
import json
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile

from . import activity, detection, firewall, generate, lists, paths, state_files
from .errors import die

# the hand-maintained lists as (record, the text file it is migrated from); the Allowlist the
# same way
LISTS = (("watchlist.json", "suspicious-domains"), ("legitimate.json", "legitimate-domains"))
ALLOWLIST = ("allowlist.json", "allowlist")
LIBVIRT_GROUP = "libvirt"
# the package's service users (rpm/agentbox.sysusers): never the owner, never who runs setup
SERVICE_USERS = ("agentbox-web", "agentbox-proxy", "agentbox-feeds", "agentbox-gh")
NO_LOGIN = ("nologin", "false")
# the running sockets of the Activity journal (ADR 0007)
JOURNAL_SOCKETS = ("stdout", "socket", "dev-log")
# the group journald runs as (stock systemd-journald@.service) and owns the runtime directory with
JOURNALD_GROUP = "systemd-journal"
# marker (generate._pending): sockets lost their group, so running writers lost their log streams
STREAMS_LOST = "journal-streams"
# the Control Room writes sign-ins with agentbox-journal as supplementary group
JOURNAL_WRITERS = "agentbox-web.service"
# what the VMs reach on the Host, each on its own network: the resolver, the proxy and the
# token service
VM_PORTS = ("53/udp", "53/tcp", "443/tcp", "9100/tcp")
EXPIRY_TIMER = "agentbox-allowlist-expire.timer"
CONTAINER_IMAGE_CLEANUP_TIMER = "agentbox-container-image-cleanup.timer"
# the VMs' proxies (agentbox regenerate writes one unit per VM)
PROXIES = "agentbox-proxy-*.service"
LIBVIRT_GUESTS_UNIT = "libvirt-guests.service"

# libvirt-guests.service shuts the running VMs down when the Host shuts down or reboots,
# instead of systemd killing QEMU (ARCHITECTURE.md, VMs; #53). It reads this file at every
# start and stop, so it is never restarted for it: its stop shuts every running VM down.
LIBVIRT_GUESTS = """\
# Generated by agentbox setup: the VMs when the Host shuts down
URIS=qemu:///system
ON_BOOT=ignore
ON_SHUTDOWN=shutdown
# all VMs at once (the registry holds at most 254)
PARALLEL_SHUTDOWN=254
# seconds until the hard power-off, like AGENTBOX_SHUTDOWN_SECONDS for Reset and Restart
SHUTDOWN_TIMEOUT=60
"""


def _run(argv):
    try:
        r = subprocess.run(argv, capture_output=True, text=True, timeout=300)
    except (OSError, subprocess.TimeoutExpired) as e:
        return die(f"{argv[0]}: {e}", error="action_failed", program=argv[0])
    if r.returncode != 0:
        die(f"{' '.join(argv)} fails: " + (r.stderr.strip()[-300:] or f"exit {r.returncode}"), error="action_failed",
            program=argv[0])
    return r


def _write_if_changed(path, data, mode=0o644):
    """Replace the file when its content or mode differs; True when it did."""
    try:
        with open(path, "rb") as f:
            if f.read() == data and stat.S_IMODE(os.fstat(f.fileno()).st_mode) == mode:
                return False
    except FileNotFoundError:
        pass
    except OSError as e:
        die(f"{path}: {e.strerror}", error="action_failed", path=path)
    state_files.write_atomic(path, data, mode)
    return True


# --- users and groups ----------------------------------------------------------------

def _getent(*args):
    """The entries of `getent <database> [<key>]`, split at ":"; none when the key is not there."""
    try:
        r = subprocess.run(["getent", *args], capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as e:
        return die(f"getent: {e}", error="action_failed", program="getent")
    if r.returncode == 2:
        return []
    if r.returncode != 0:
        die(f"getent {' '.join(args)} fails: " + (r.stderr.strip()[-200:] or f"exit {r.returncode}"),
            error="action_failed", program="getent")
    return [line.split(":") for line in r.stdout.splitlines() if line]


def uid_min():
    """The lowest uid of a person's account: UID_MIN of /etc/login.defs, 1000 without it."""
    try:
        with open(paths.LOGIN_DEFS, encoding="utf-8", errors="replace") as f:
            for line in f:
                m = re.fullmatch(r"\s*UID_MIN\s+(\d+)\s*(#.*)?\s*", line)
                if m:
                    return int(m.group(1))
    except OSError:
        pass
    return 1000


def _passwd(name):
    """{"name", "uid", "gid", "home", "shell"} of a user, or None when there is none."""
    rows = _getent("passwd", name)
    if not rows or len(rows[0]) < 7 or not rows[0][2].isdigit() or not rows[0][3].isdigit():
        return None
    row = rows[0]
    return {"name": row[0], "uid": int(row[2]), "gid": int(row[3]), "home": row[5], "shell": row[6]}


def _login_user(user):
    """A person's account: none of the package's service users, a uid of a person, a shell."""
    return (user["name"] not in SERVICE_USERS and user["uid"] >= uid_min()
            and os.path.basename(user["shell"]) not in NO_LOGIN)


def check_caller():
    """setup is the owner's, at the Host. Through sudo, the user who called it (SUDO_USER and
    SUDO_UID, which sudo sets itself) must be root or a person: the Control Room's sudo rule
    lets agentbox-web run agentbox with any arguments, and setup would put it into libvirt
    (control of every VM) or change how the Host is exposed. Reads only."""
    name = os.environ.get("SUDO_USER")
    if not name:
        return
    uid = os.environ.get("SUDO_UID", "")
    if uid.isdigit():
        uid = int(uid)
    else:
        user = _passwd(name)
        uid = user["uid"] if user else None
    if name in SERVICE_USERS or uid is None or 0 < uid < uid_min():
        die(f"setup is for the owner at the Host, not for {name} (a service or system user) through sudo",
            error="action_failed", user=name)


def owner(name):
    """The owner user (owner_user of the Host setup) as {"name", "uid", "gid", "home", "shell"}; stops
    when there is no such user or it is no person's account: the owner goes into libvirt, which
    controls every VM. Reads only."""
    user = _passwd(name)
    if user is None:
        die(f"there is no user {name}", error="action_failed", user=name)
    if not _login_user(user):
        die(f"{name} cannot be the owner: not a person's account (uid {user['uid']}, shell "
            f"{user['shell']}; needed: uid {uid_min()} or above, a shell, no service user of Agent Box)",
            error="action_failed", user=name)
    return user


def _group(name, comes_with):
    rows = _getent("group", name)
    if not rows or len(rows[0]) < 4 or not rows[0][2].isdigit():
        die(f"the group {name} is missing ({comes_with})", error="action_failed", group=name)
    return int(rows[0][2]), {m for m in rows[0][3].split(",") if m}


def groups(user):
    """The owner in libvirt, so they control the VMs without root. agentbox-journal, who may
    write Activity besides root (ADR 0007), gets exactly the members of libvirt, as primary or
    supplementary group: who controls every VM may also record (agentbox pair without root)."""
    said = []
    gid, members = _group(LIBVIRT_GROUP, "comes with libvirt")
    if user["gid"] != gid and user["name"] not in members:
        _run(["usermod", "-aG", LIBVIRT_GROUP, user["name"]])
        said.append(f"{user['name']} in the group {LIBVIRT_GROUP} (applies from the next sign-in)")
        gid, members = _group(LIBVIRT_GROUP, "comes with libvirt")
    wanted = members | {row[0] for row in _getent("passwd") if len(row) > 3 and row[3] == str(gid)}
    _, journal = _group(activity.JOURNAL_GROUP, "the package creates it")
    if journal != wanted:
        _run(["gpasswd", "-M", ",".join(sorted(wanted)), activity.JOURNAL_GROUP])
        said.append(f"{activity.JOURNAL_GROUP}: {', '.join(sorted(wanted)) or 'nobody'} (as {LIBVIRT_GROUP})")
    return said


def journal_sockets():
    """The running sockets of the Activity journal: only root and agentbox-journal write there
    (ADR 0007). The package's drop-in gives them group and mode when systemd creates them, and
    its tmpfiles entry makes the directory root:systemd-journal, journald's own owner. A
    directory owned otherwise (root:root) makes systemd chown it and everything in it to
    root:systemd-journal when journald starts the first time, which takes the group from the
    sockets. So the directory is set right first, then the sockets' group and mode in place,
    without a restart of journald that would cut the log streams of running services. Services
    whose connect failed have their output in /dev/null until they restart: the proxies and
    the Control Room restart when a socket's group changed, and again in a later run when that
    restart failed (a marker, removed once it succeeded). The group only as root (tests run as a normal
    user)."""
    root = os.geteuid() == 0
    gid = _group(activity.JOURNAL_GROUP, "the package creates it")[0] if root else -1
    said = []
    folder = activity.JOURNAL_RUN
    journald = _group(JOURNALD_GROUP, "comes with systemd")[0] if root else -1
    try:
        st = os.lstat(folder)
        if journald != -1 and stat.S_ISDIR(st.st_mode):
            changed = (st.st_uid, st.st_gid) != (0, journald)
            if changed:
                os.chown(folder, 0, journald)
            if stat.S_IMODE(st.st_mode) != 0o755:
                os.chmod(folder, 0o755)
                changed = True
            if changed:
                said.append(f"{folder}: root:{JOURNALD_GROUP}, mode 755")
    except FileNotFoundError:
        pass
    except OSError as e:
        die(f"{folder}: {e.strerror}", error="action_failed", path=folder)
    for name in JOURNAL_SOCKETS:
        path = os.path.join(folder, name)
        try:
            st = os.lstat(path)
            if not stat.S_ISSOCK(st.st_mode):
                continue
            changed = gid != -1 and st.st_gid != gid
            if changed:
                generate._mark(STREAMS_LOST)       # before the chown: a run that dies still restarts
                os.chown(path, -1, gid)
            if stat.S_IMODE(st.st_mode) != 0o660:
                os.chmod(path, 0o660)
                changed = True
        except FileNotFoundError:
            continue
        except OSError as e:
            die(f"{path}: {e.strerror}", error="action_failed", path=path)
        if changed:
            said.append(f"{path}: {activity.JOURNAL_GROUP}, mode 660")
    if os.path.exists(generate._pending(STREAMS_LOST)):
        _systemctl("try-restart", PROXIES, JOURNAL_WRITERS)
        os.remove(generate._pending(STREAMS_LOST))
        said.append("running proxies and the Control Room restarted to reconnect their log streams")
    return said


# --- files ---------------------------------------------------------------------------

def directories():
    """/var/lib/agentbox with images and vms (the package brings them). One made here goes
    without copy-on-write, which slows VM disks down a lot on btrfs; on other file systems
    chattr refuses, which is fine, as in the package's %post."""
    said = []
    for path, mode in ((paths.STATE, 0o755), (paths.IMAGES, 0o711), (paths.VMS, 0o711)):
        try:
            new = not os.path.isdir(path)
            if new:
                os.mkdir(path, mode)
            if stat.S_IMODE(os.stat(path).st_mode) != mode:
                os.chmod(path, mode)
                if not new:
                    said.append(f"{path}: mode {mode:o}")
        except OSError as e:
            die(f"{path}: {e.strerror}", error="action_failed", path=path)
        if new:
            said.append(f"{path} created" + (" (without copy-on-write)" if path != paths.STATE and _nocow(path)
                                             else ""))
    return said


def _nocow(path):
    try:
        return subprocess.run(["chattr", "+C", path], capture_output=True, timeout=60).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def _conf(name):
    return os.path.join(paths.CONF, name)


def list_source(record, legacy):
    """The file a list of the Host comes from: its record; before the migration its text file;
    on a new Host (neither, nor the text file moved aside by the migration) the one of the
    Release; None for a record lost after the migration, which the Release's list would replace
    with a stale one and so open Open web again."""
    for path in (_conf(record), _conf(legacy)):
        if os.path.isfile(path):
            return path
    if not os.path.exists(_conf(legacy + ".migrated")):
        return os.path.join(paths.SEED_LISTS, legacy)
    return None


def self_test():
    """The detection self-test (ARCHITECTURE.md, Detection) of the installed proxy and
    classifier, with each list as it will apply (list_source; a lost one empty). A broken record
    of the Host fails it, and setup stops before it changes anything."""
    copies = {}
    with tempfile.TemporaryDirectory(prefix="agentbox-selftest.") as folder:
        for record, legacy in LISTS:
            source = list_source(record, legacy)
            try:
                if source:
                    copies[os.path.join(folder, os.path.basename(source))] = source
                    shutil.copyfile(source, os.path.join(folder, os.path.basename(source)))
                else:
                    with open(os.path.join(folder, record), "w") as f:
                        f.write('{"entries": []}\n')
            except OSError as e:
                die(f"{e.filename}: {e.strerror}", error="action_failed", path=e.filename)
        try:
            r = subprocess.run([sys.executable, "-I", "-B", paths.SUSPICIOUS, "--self-test"], capture_output=True,
                               text=True, env=dict(os.environ, AGENTBOX_CONF_DIR=folder), timeout=300)
        except (OSError, subprocess.TimeoutExpired) as e:
            die(f"{paths.SUSPICIOUS}: {e}", error="action_failed")
    if r.returncode != 0:
        said = "; ".join(line.split(None, 1)[-1] for line in r.stdout.splitlines() if line.startswith("FAILED"))
        for copy, source in copies.items():        # the Host's files, not the copies
            said = said.replace(copy, source)
        die(said[:600] or r.stderr.strip()[-300:] or f"exit {r.returncode}", error="action_failed")
    return ["passed"]


def _seed(name, dest):
    source = os.path.join(paths.SEED_LISTS, name)
    try:
        with open(source, "rb") as f:
            data = f.read()
    except OSError as e:
        die(f"{source}: {e.strerror} (the Release is not installed completely)", error="action_failed",
            path=source)
    state_files.write_atomic(dest, data, 0o644)
    return f"{os.path.basename(dest)} from {paths.SEED_LISTS}"


LOST = {
    "watchlist.json": "Open web stays closed until it is back (or until the admin creates a new one with "
                      "agentbox watch-add <domain> --category <category> --force; the Control Room cannot)",
    "legitimate.json": "agentbox migrate-lists creates it empty, only the built-in Legitimate domains count",
}


def seed_lists(warn):
    """The Allowlist, Watchlist and Legitimate domains a new Host starts with, as the text files
    agentbox migrate-allowlist and migrate-lists (later steps) take over into records; from then
    on only agentbox changes them, and later Releases' lists do not reach the Host. The file of
    Harmless marks, empty."""
    said = []
    for record, legacy in LISTS:
        source = list_source(record, legacy)
        if source == os.path.join(paths.SEED_LISTS, legacy):
            said.append(_seed(legacy, _conf(legacy)))
        elif source is None:
            warn(f"WARNING: {_conf(record)} is missing, but was taken over already ({legacy}.migrated); the "
                 f"Release's list would be stale and is not put there: {LOST[record]}. To restore it: from a "
                 f"backup, or the state of the takeover with mv {_conf(legacy)}.migrated {_conf(legacy)} && "
                 "agentbox migrate-lists")
    if not any(os.path.exists(_conf(name)) for name in ALLOWLIST):
        said.append(_seed(ALLOWLIST[1], _conf(ALLOWLIST[1])))
    harmless = detection.harmless_file()
    try:
        if not os.path.exists(harmless):
            state_files.write_atomic(harmless, detection.HARMLESS_HEADER, 0o644)
            said.append(f"{os.path.basename(harmless)} created (empty)")
        elif stat.S_IMODE(os.stat(harmless).st_mode) != 0o644:
            os.chmod(harmless, 0o644)
            said.append(f"{os.path.basename(harmless)}: mode 644")
    except OSError as e:
        die(f"{harmless}: {e.strerror}", error="action_failed", path=harmless)
    return said


# --- firewall and units ------------------------------------------------------------------

def libvirt_zone():
    """firewalld puts the bridges of the VM networks into the zone libvirt: the resolver, the
    proxy and the token service are reachable there, ssh to the Host is not."""
    changed = firewall.ensure("libvirt", add=[("port", p) for p in VM_PORTS], remove=[("service", "ssh")])
    words = {("add", "port"): "port {} open", ("remove", "service"): "service {} removed"}
    return [words.get((verb, kind), f"{verb} {kind} {{}}").format(value) for verb, kind, value in changed]


def _systemctl(*args):
    return _run(["systemctl", *args])


def _query(*args):
    try:
        return subprocess.run(["systemctl", *args], capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as e:
        return die(f"systemctl {' '.join(args)}: {e}", error="action_failed", program="systemctl")


def enable(unit, start=True):
    """The unit enabled (at boot) and, with start, running; only what is not so already."""
    said = []
    if _query("is-enabled", unit).stdout.strip() != "enabled":
        _systemctl("enable", unit)
        said.append(f"{unit} enabled")
    if start and _query("is-active", unit).returncode != 0:
        _systemctl("start", unit)
        said.append(f"{unit} started")
    return said


def vm_rules():
    """agentbox-vmnet.service loads the rules that let each VM reach only the proxy and the token
    service on its network (vm-input.nft): without it VMs are not restricted after a reboot.
    Enabled before any VM can start; started here when the rules are there, else agentbox
    regenerate writes them and starts it before it brings up a VM network."""
    return enable(generate.VMNET, start=os.path.exists(generate.VM_RULES))


def libvirt_guests():
    said = [f"{paths.LIBVIRT_GUESTS} written"] if _write_if_changed(paths.LIBVIRT_GUESTS,
                                                                         LIBVIRT_GUESTS.encode()) else []
    return said + enable(LIBVIRT_GUESTS_UNIT)


def expiry_timer():
    """The timer that removes expired Temporary allowlist entries, every minute."""
    return enable(EXPIRY_TIMER)


def container_image_cleanup_timer():
    """The timer of the Container image cleanup in the running VMs, every hour."""
    return enable(CONTAINER_IMAGE_CLEANUP_TIMER)


def proxies_before_lists():
    """The running proxies restarted onto the installed code while there are text lists for
    migrate-lists (the next step) to take over: code from before the records reads only those
    files, so once they are moved aside it would go on without the Host's Watchlist and Legitimate
    domains. regenerate has loaded the VMs' units before, so they start what this Release's units
    name. Their sockets stay, so a VM loses only the connections open through its proxy; a proxy
    that does not run stays stopped. With nothing to migrate nothing restarts, so a second run
    changes nothing."""
    if not any(os.path.isfile(_conf(legacy)) for _, legacy in LISTS):
        return []
    _systemctl("try-restart", PROXIES)
    return ["running proxies restarted before the lists are taken over"]


def first_feeds():
    """The Feeds fetched right away on a new Host instead of when their timer (regenerate) is
    first due; only while none was ever fetched (no status.json)."""
    if os.path.exists(os.path.join(paths.FEEDS, "status.json")):
        return []
    _systemctl("start", "--no-block", f"{generate.FEEDS}.service")
    return ["the first Feeds are being fetched (journalctl -t agentbox-feeds)"]


# --- the migrations, as commands of their own ----------------------------------------------

def command(*args):
    """Another command of this CLI in a call of its own (its own Activity entry, with the actor
    of this call); its --json answer. Its failure, which --json reports as one JSON object on
    stderr, ends this command with its message, code and parameters."""
    code = "import sys; sys.path.insert(0, sys.argv.pop(1)); from agentbox.cli import main; sys.exit(main())"
    argv = [sys.executable, "-I", "-c", code, paths.CODE, f"--actor={activity.actor()}", *args, "--json"]
    try:
        r = subprocess.run(argv, capture_output=True, text=True, timeout=1800)
    except (OSError, subprocess.TimeoutExpired) as e:
        return die(f"agentbox {args[0]}: {e}", error="action_failed", command=args[0])
    said, failure = [], {}
    for line in r.stderr.splitlines():
        if not line.strip():
            continue
        try:
            reported = json.loads(line)
        except ValueError:
            reported = None
        if (isinstance(reported, dict) and isinstance(reported.get("error"), str)
                and isinstance(reported.get("message"), str)):
            failure = reported
            said.append(reported["message"])
        else:
            said.append(line.removeprefix("agentbox: "))
    if r.returncode != 0:
        params = failure.get("params") if isinstance(failure.get("params"), dict) else {}
        die("; ".join(said)[-400:] or f"agentbox {args[0]}: exit {r.returncode}",
            error=failure.get("error", "action_failed"),
            **{k: v for k, v in params.items() if k not in ("message", "exit", "error", "raw")})
    for line in said:
        print(f"agentbox: {line}", file=sys.stderr)
    try:
        return json.loads(r.stdout)
    except ValueError:
        return die(f"agentbox {args[0]}: unexpected answer", error="action_failed", command=args[0])


def migrate():
    """work and priv from before the VM registry into it (once; nothing on a new Host)."""
    return [f"{r['vm']}: taken over into the registry" for r in command("migrate") if r["action"] == "migrated"]


def migrate_allowlist():
    result = command("migrate-allowlist")
    return [result["message"]] if result["files"] else []


def migrate_lists():
    result = command("migrate-lists")
    return [] if result["message"] == lists.NOTHING_TO_MIGRATE else [result["message"]]
