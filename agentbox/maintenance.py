"""The Maintenance window (#49): the Host's daily maintenance, at one time of day.

agentbox-maintenance.timer (generated by `agentbox regenerate`, daily at maintenance_time of the
Settings, Persistent, so a window missed while the Host was off runs once after boot) starts
agentbox-maintenance.service, which runs `agentbox --actor=timer maintenance`: these steps one
after another, each only once the one before it has finished:

  1. feeds        the Feeds fetched (agentbox-feeds.service, as agentbox-feeds; its own timer
                  still fetches them every feed_interval_hours on a Host that is awake for long)
  2. versions     the version check (agentbox-versions.service: the fetch as agentbox-feeds,
                  then `check-versions`), which with auto_update starts the Builds of every Image
                  with an update (images.start_automatic); the window waits until no Build runs
  3. rebuild      on rebuild_day the weekly Build of every Image (agentbox-build@all), and again
                  the wait; also on the first window after a rebuild_day whose window was missed
  4. reset-check  the Reset check (lifecycle.reset_check): Reset by age, and with auto_update
                  idle VMs moved onto their Image's newer Build; only when idle, as always

Waiting for the Builds is waiting for the run lock (images.RUN_LOCK) and their units
(images.building): the Reset check never begins while a Build of the window runs, so the VMs it
moves get the Build that was just made, and a failed Build, which never becomes the current one,
moves no VM.

A step that fails is recorded in Activity (maintenance.<step>, outcome failed, the actor of the
call: `timer`) and the window goes on with the next one; a step that succeeded is recorded too,
so the timeline shows the window's order. A rebuild that is not due records nothing. A step
whose Builds failed counts as failed. Two windows never run at once.
"""
import datetime
import json
import os
import re
import subprocess
import time

from . import activity, images, lifecycle, paths, settings, state_files
from .errors import Fail, die
from .sanitize import clean

LOCK = os.path.join(paths.STATE, "maintenance")
RECORD = os.path.join(paths.STATE, "maintenance.json")      # the date of the last weekly rebuild it started
FEEDS_UNIT = "agentbox-feeds.service"
VERSIONS_UNIT = "agentbox-versions.service"
START_SECONDS = 3 * 3600        # systemctl start of a step's unit; the units have time limits of their own
POLL = paths.tunable("AGENTBOX_MAINTENANCE_POLL_SECONDS", 15)     # between two looks at the Builds
DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
# the steps in their order, with what the Activity entries and the journal call them
STEPS = (("feeds", "fetching the Feeds", "Feeds fetched"),
         ("versions", "version check", "version check done"),
         ("rebuild", "weekly rebuild of every Image", "weekly rebuild of every Image done"),
         ("reset-check", "Reset check", "Reset check done"))


def _start(unit):
    """systemctl start: the unit's run (a oneshot service) to its end."""
    try:
        r = subprocess.run(["systemctl", "start", unit], capture_output=True, text=True, errors="replace",
                           timeout=START_SECONDS)
    except (OSError, subprocess.TimeoutExpired) as e:
        die(f"systemctl start {unit}: {type(e).__name__}", error="action_failed", unit=unit)
    if r.returncode != 0:
        die(f"systemctl start {unit} failed: " + (clean(r.stderr.strip(), False)[-300:] or f"exit {r.returncode}"),
            error="action_failed", unit=unit)


def wait_for_builds(say):
    """Until no Build runs or is about to (images.building): blocks on the run lock while a Build
    holds it, and looks again every POLL seconds while a unit of a Build is active without it."""
    if not images.building():
        return
    say("Waiting for the Builds to finish")
    while True:
        with state_files.locked(images.RUN_LOCK):
            pass
        if not images.building():
            say("The Builds have finished")
            return
        time.sleep(POLL)


def _builds_done(started, target):
    """After waiting: a Fail when a Build of agentbox-build@<target> begun since `started` failed."""
    failed = images.failed_since(started, target)
    if failed:
        die(f"the Build of {', '.join(failed)} failed", error="action_failed")


def rebuild_due(now, day, at, last):
    """Whether a window at `now` (epoch seconds, local time) starts the weekly rebuild: day (of
    DAYS) and at (HH:MM) are rebuild_day and maintenance_time, last the date of the last weekly
    rebuild a window started (None: never). Due when no rebuild began on or after the date of the
    last window due on rebuild_day (so a missed one is caught up by the next window, once);
    without a record only on rebuild_day itself."""
    local = datetime.datetime.fromtimestamp(now)
    hours, minutes = map(int, at.split(":"))
    when = (local - datetime.timedelta(days=(local.weekday() - settings.DAYS.index(day)) % 7)).replace(
        hour=hours, minute=minutes, second=0, microsecond=0)
    if when > local:
        when -= datetime.timedelta(days=7)
    return when.date() == local.date() if last is None else last < when.date()


def _last_rebuild():
    try:
        with open(RECORD, encoding="utf-8") as f:
            value = json.load(f).get("rebuild")
        return datetime.date.fromisoformat(value) if isinstance(value, str) and DATE.fullmatch(value) else None
    except (OSError, ValueError, AttributeError):
        return None


def _feeds(say, begun):
    _start(FEEDS_UNIT)


def _versions(say, begun):
    started = int(time.time())
    _start(VERSIONS_UNIT)
    wait_for_builds(say)
    _builds_done(started, images.UPDATE)


def _rebuild(say, begun):
    """Due or not by the time the window began, however long the Builds before took."""
    values = settings.load()
    if not rebuild_due(begun, values["rebuild_day"], values["maintenance_time"], _last_rebuild()):
        say(f"No weekly rebuild today (rebuild_day: {values['rebuild_day']})")
        return "skipped"
    started = int(time.time())
    name = images.start("all")
    os.makedirs(paths.STATE, exist_ok=True)
    state_files.write_atomic(RECORD, (json.dumps({"rebuild": datetime.date.fromtimestamp(begun).isoformat()})
                                      + "\n").encode(), 0o644)
    say(f"Weekly rebuild started ({name})")
    wait_for_builds(say)
    _builds_done(started, "all")
    return "ok"


def _reset_check(say, begun):
    results, failed = lifecycle.reset_check()
    if failed:
        vms = [r["vm"] for r in results if r["action"] == "failed"]
        die(f"failed for {', '.join(vms)}", failed, error="action_failed")


RUN = {"feeds": _feeds, "versions": _versions, "rebuild": _rebuild, "reset-check": _reset_check}


def _record(step, what, done, failure=None):
    if failure is None:
        activity.record("action", f"maintenance.{step}", f"Maintenance window: {done}")
        return
    error, message, params = failure
    activity.record("action", f"maintenance.{step}", f"Maintenance window: {what} failed: {message}",
                    outcome="failed", error=error, error_params=params)


def maintenance(args):
    """agentbox maintenance [--json] (agentbox-maintenance.service, daily at maintenance_time): the
    Maintenance window, its steps one after another; a failing one does not stop the next."""
    if any(a != "--json" for a in args):
        die("maintenance [--json]", error="invalid_argument")
    as_json = "--json" in args
    say = (lambda line: None) if as_json else (lambda line: print(clean(line, False), flush=True))
    results, begun = [], time.time()
    with state_files.locked_unless_held(LOCK) as mine:
        if not mine:
            die("a Maintenance window is running already (journalctl -fu agentbox-maintenance)",
                error="action_failed")
        for step, what, done in STEPS:
            say(f"== Maintenance window: {what}")
            try:
                outcome, message = RUN[step](say, begun) or "ok", None
            except Fail as f:
                message = clean(f.message.strip(), False) or f"exit {f.exit}"
                outcome = "failed"
                say(f"Maintenance window: {what} failed: {message}")
                _record(step, what, done, (f.error, message, f.params))
            except Exception as e:     # noqa: BLE001  one step's fault must not keep the next from running
                message, outcome = f"internal error ({type(e).__name__})", "failed"
                say(f"Maintenance window: {what} failed: {message}")
                _record(step, what, done, ("unexpected_error", message, {"type": type(e).__name__}))
            else:
                if outcome == "ok":
                    _record(step, what, done)
            results.append({"step": step, "outcome": outcome, "message": message})
    if as_json:
        print(json.dumps({"steps": results}))
    if any(r["outcome"] == "failed" for r in results):
        raise Fail("", 1, error="action_failed", raw=True)


COMMANDS = {"maintenance": maintenance}
