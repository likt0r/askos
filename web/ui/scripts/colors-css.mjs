// Writes app/assets/css/colors.css: the CSS variables Nuxt UI's colors plugin would
// inject at runtime (disabled, see nuxt.config.ts), from app.config.ts's colors.
// Run after changing the colors: node scripts/colors-css.mjs
import { writeFileSync } from 'node:fs'
import colors from 'tailwindcss/colors'

const ui = {
  primary: 'blue', secondary: 'indigo', success: 'green', info: 'sky',
  warning: 'amber', error: 'red', neutral: 'stone',
}
const shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
const shade = (key, value) => shades.map(s =>
  `    --ui-color-${key}-${s}: var(--color-${value === 'neutral' ? 'old-neutral' : value}-${s}, ${colors[value][s]});`)
const others = Object.keys(ui).filter(k => k !== 'neutral')
const css = `/* Generated by scripts/colors-css.mjs, keep in sync with app/app.config.ts */
@layer theme {
  :root, :host {
${Object.entries(ui).flatMap(([k, v]) => shade(k, v)).join('\n')}
  }
  :root, :host, .light {
${others.map(k => `    --ui-${k}: var(--ui-color-${k}-500);`).join('\n')}
  }
  .dark {
${others.map(k => `    --ui-${k}: var(--ui-color-${k}-400);`).join('\n')}
  }
}
`
writeFileSync(new URL('../app/assets/css/colors.css', import.meta.url), css)
